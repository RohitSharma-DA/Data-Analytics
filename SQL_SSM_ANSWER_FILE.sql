------------------------------------------------------------------------------------------------------------------------------------------------
-----------Write a query that displays Order ID, order date, customer name, customer region, product name, quantity ordered, and selling price--
-------------------per unit. Combine the required tables and return the complete order-level product details.-----------------------------------
------------------------------------------------------------------------------------------------------------------------------------------------
select o.OrderID, o.OrderDate,c.CustomerName,c.Region, p.ProductName, od.Quantity, od.UnitPrice*od.Quantity as [Selling Price]
from Orders o
join Customers c
on c.CustomerID = o.CustomerID
join OrderDetails od
on o.OrderID = od.OrderID
join Products p
on p.ProductID = od.ProductID;


