-----------------------------------------------------------------
--The sales manager wants to identify high-performing products.--
--Write a query that returns products with total sales revenue greater than n50,000. Display the product name, total quantity sold, total--
--revenue, and total profit.
--Calculate revenue using OrderDetails.Quantity × OrderDetails.UnitPrice and profit using (selling price - product unit cost) × quantity.

select
    p.ProductName,
    SUM(od.Quantity) AS TotalQuantity,
    SUM(od.UnitPrice * od.Quantity) AS TotalRevenue,
    SUM(p.UnitCost * od.Quantity) AS TotalCost,
    SUM((od.UnitPrice - p.UnitCost) * od.Quantity) AS TotalProfit
from Products p
join OrderDetails od
on p.ProductID = od.ProductID
group by p.ProductID, p.ProductName
having SUM(od.UnitPrice * od.Quantity) > 50000;


