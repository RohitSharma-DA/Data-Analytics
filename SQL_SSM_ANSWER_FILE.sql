-------------------------------------------------------------
---------------Customers who have never placed an order.-----
-------------------------------------------------------------

select c.CustomerID,c.CustomerName,c.City,c.Region
from Customers c
left join Orders o
on o.CustomerID=c.CustomerID
where o.OrderID is null;

-------------------------------------------------------------
--------------Products that have never been ordered----------
-------------------------------------------------------------
SELECT p.ProductID, p.ProductName, p.Category
FROM Products p
LEFT JOIN OrderDetails od
    ON od.ProductID = p.ProductID
WHERE od.ProductID IS NULL;

-------------------------------------------------------------------
-----------Orders that contain no matching order-detail records.---
-------------------------------------------------------------------
select o.*
from Orders o
left join OrderDetails od
on o.OrderID=od.OrderID
where od.OrderDetailID is null;

------------------------------------------------------------------
-----Duplicate customer records based on customer name and city.--
------------------------------------------------------------------
select CustomerID,CustomerName, City, Region, COUNT(*) [DuplicateCnt]
from Customers
group by CustomerID,CustomerName, City, Region
having count(*) >1;
