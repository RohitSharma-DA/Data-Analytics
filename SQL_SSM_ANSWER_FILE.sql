--Using a CTE, calculate total revenue generated by each customer.
--Return the customer ID, customer name, total revenue, and customer ranking from highest to lowest revenue.

WITH OrdersPerCustomer AS (
    select
        o.CustomerID,
        ROUND(SUM(od.UnitPrice * od.Quantity), 2) AS TotalRevenue,
        DENSE_RANK() OVER (
            order by SUM(od.UnitPrice * od.Quantity) desc
        ) as rnk
    from Orders o
    join OrderDetails od
        on od.OrderID = o.OrderID
    group by o.CustomerID
)
select
    c.CustomerID,
    c.CustomerName,
    oc.TotalRevenue,
    oc.rnk as [Rank]
from Customers c
JOIN OrdersPerCustomer oc
    on c.CustomerID = oc.CustomerID
order by oc.rnk;


